Tout commence par un repérage du lieu. Hauteur sous plafond, prises, accroches possibles, voisinage et horaire de montage déterminent le matériel. Un lieu magnifique peut se révéler très réverbérant, ou ne pas supporter la puissance électrique d'un dispositif de concert.

Le repérage permet de vérifier :

- les dimensions de la salle et l'emplacement possible de la scène ;
- la puissance électrique disponible et l'emplacement des prises ;
- les points d'accroche pour la lumière et les enceintes ;
- l'acoustique, et les éventuelles limites sonores imposées par le lieu ;
- l'accès pour le matériel et le temps de montage autorisé.

## Quel matériel selon le type d'événement ?

Une conférence intimiste n'a pas besoin du dispositif d'un concert. Le besoin dépend avant tout de ce que le public doit voir et entendre :

- Conférence ou séminaire : une sonorisation claire pour la parole, des micros fiables, un écran lisible et un éclairage de scène qui met les intervenants en valeur.
- Soirée de gala : une lumière d'ambiance qui habille la salle, une sonorisation pour les discours et la musique, et des effets mesurés pour les temps forts.
- Concert ou show : un système de diffusion dimensionné pour le public, des retours pour les artistes et une lumière scénique, avec un [live band](/activites/live-band) ou un DJ.
- Cocktail ou inauguration : une diffusion répartie dans l'espace, à volume modéré, pour que les invités puissent se parler.

## Mur LED ou vidéoprojection ?

Un mur LED ou une vidéoprojection se justifie s'il porte un contenu, pas pour remplir un devis. Le mur LED reste lisible dans une salle éclairée ou en extérieur, et s'adapte à des formats variés. La vidéoprojection convient bien aux salles que l'on peut assombrir. Dans les deux cas, la taille de l'image se décide selon la distance du dernier rang et le contenu affiché : un texte de présentation demande plus de lisibilité qu'une vidéo d'ambiance.

## Qu'est-ce qu'un plan d'implantation ?

Le plan d'implantation se partage avec l'organisateur et le lieu avant l'installation. Il fixe le passage des câbles, la place de la régie et la circulation du public. Il indique aussi l'emplacement des enceintes, des projecteurs, des écrans et des pupitres.

Ce document évite les débats le jour du montage : chacun sait où se placent la scène, le traiteur et la décoration. Il sert également à vérifier la sécurité, notamment les câbles dans les zones de passage et les issues de secours dégagées.

## Quand faire les tests ?

Les tests se font avant l'accueil des invités, avec les intervenants quand c'est possible : micro, retours, première diapositive, première musique. Une répétition, même courte, permet à un intervenant de trouver sa place sur scène et à la régie de caler les enchaînements. Prévoyez du matériel de secours pour les éléments critiques, comme un micro supplémentaire ou un second ordinateur de diffusion.

