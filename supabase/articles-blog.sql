## Pourquoi un seul chef de projet ?

Sur un événement d'entreprise, une dizaine de métiers interviennent : lieu, traiteur, son et lumière, décoration, print, transport, animation, photo et vidéo. Quand chacun a son propre interlocuteur côté client, les informations se perdent. Un changement d'horaire validé avec le traiteur n'arrive pas à la régie ; une modification du nombre d'invités ne remonte pas jusqu'aux badges.

Le chef de projet est le point d'entrée unique. Il connaît le brief, le budget et le planning, et il répercute chaque décision à tous les métiers concernés. Pour l'entreprise, cela signifie un seul numéro à appeler et une seule personne qui répond de l'ensemble.

## Comment définir le concept ?

Le concept vient du but de la journée. Une plénière qui doit faire passer un message n'a pas le même rythme qu'une soirée de gala, une inauguration ou un family day. Avant de parler décor, le chef de projet pose quelques questions :

- Qu'est-ce que les invités doivent retenir en repartant ?
- Qui sont-ils, et combien seront-ils ?
- Quel est le ton attendu : institutionnel, festif, inspirant ?
- Quels sont les temps forts incontournables : discours, remise de prix, annonce ?

Les réponses donnent un fil conducteur : un nom, une identité visuelle, une ambiance. C'est lui qui guide ensuite les choix de lieu, de décor, de [communication](/univers/communication) et de [technique](/univers/lumiere-sono).

## Comment choisir le lieu d'un séminaire ou d'un gala ?

Le lieu se choisit ensuite : capacité réelle une fois la scène et les allées posées, accès livraisons, lumière du jour, et ce que le site permet vraiment d'installer. Une salle annoncée pour trois cents personnes en cocktail n'en accueille pas autant en dîner assis avec une scène.

Le chef de projet vérifie aussi les horaires de montage et de démontage, les contraintes sonores, la puissance électrique disponible, l'hébergement pour un séminaire résidentiel et le temps de trajet depuis l'aéroport ou la gare. Une visite sur place, avec la technique, évite la plupart des mauvaises surprises.

## Comment construire le budget ?

Le budget se construit ligne par ligne : lieu, restauration, technique, print, animation, logistique. Réunir ces métiers dans la même équipe permet de les voir ensemble. La sono, les badges et l'accueil ne doivent pas être trois devis qui se découvrent la veille.

Un budget lisible distingue ce qui est fixe (le lieu, la scène) de ce qui varie avec le nombre d'invités (restauration, badges, cadeaux). Il permet d'arbitrer en connaissance de cause : réduire un poste décoratif pour renforcer la technique, par exemple, si le message passe surtout par la scène.

## Quel calendrier prévoir ?

Le rétroplanning part de la date et remonte : confirmation du lieu, envoi du save-the-date, validation du concept, commandes de fabrication, invitations, BAT des imprimés, répétitions. Certaines étapes ont des délais incompressibles : la fabrication d'un décor ou de goodies, l'impression de grands formats, la disponibilité des lieux les plus demandés. Plus l'événement est important, plus il faut s'y prendre tôt.

## Que fait le chef de projet le jour J ?

Le jour J, le chef de projet est sur site. Il tient le planning, parle aux prestataires et laisse les hôtes accueillir leurs invités.

Concrètement, il suit le conducteur minute par minute, vérifie l'installation avant l'ouverture des portes, briefe l'équipe d'accueil, coordonne la régie et le traiteur, et règle les imprévus sans les faire remonter à la direction : un intervenant en retard, un changement d'ordre des prises de parole, une averse avant un cocktail en extérieur.

## Et après l'événement ?

Après l'événement, un bilan partagé remet à plat ce qui a fonctionné et ce qu'il faudra ajuster la fois suivante. Il réunit les retours des invités, les photos et vidéos, le suivi du budget et les points d'amélioration. Pour un événement récurrent, ce bilan est la première page du prochain brief.

