Le jour de l'ouverture, le stand doit être prêt, pas en cours de finition. Transport, montage et démontage font partie de la prestation, avec un seul interlocuteur. La signalétique et les supports print se posent en même temps, pour que l'espace et les documents racontent la même marque.

Pendant le salon, prévoyez de quoi accueillir correctement : supports de présentation, documentation, rangements discrets, et un écran ou une animation si elle sert le message. Un stand vivant attire plus qu'un stand seulement décoré.

## Comment préparer la prochaine édition ?

Le démontage se prévoit aussi sérieusement que le montage : ce qui se réemploie, ce qui se stocke, ce qui a servi et ne reviendra pas. C'est souvent là que se prépare déjà la prochaine édition.

Faites un bilan rapide avec les équipes présentes : nombre de contacts, questions les plus posées, zones du stand les plus fréquentées, ce qui a manqué. Ces retours, ajoutés aux éléments réutilisables, rendent le stand suivant plus efficace.

